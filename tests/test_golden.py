"""
Golden-vector test: compares the Python engine against spec/orbs-golden.json from the
thinking-orbs repo (generated by the original JS engine). 72 cases: 9 states x 2 sizes
x 4 timestamps. Usage:  python tests/test_golden.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from thinking_orbs import orb_frame, resolvePreset

path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "orbs-golden.json")
g = json.load(open(path))
tol = g["tolerance"]

# 1. resolved presets
for key, ref in g["resolved"].items():
    state, size = key.rsplit("-", 1)
    mode, speed, opts = resolvePreset(state, int(size))
    assert mode == ref["mode"] and speed == ref["speed"], key
    for k, v in ref["opts"].items():
        assert abs(opts[k] - v) < 1e-9, (key, k, opts[k], v)
    assert set(opts) == set(ref["opts"]), (key, set(opts) ^ set(ref["opts"]))

# 2. every dot / line of every case
worst = 0.0
fails = 0
values = 0
for case in g["cases"]:
    dots, lines = orb_frame(case["state"], case["size"], case["t"])
    ok = len(dots) == case["dotCount"] and len(lines) == case["lineCount"]
    flat_d = [v for d in dots for v in d]
    flat_l = [v for l in lines for v in l]
    if ok:
        for a, b in zip(flat_d + flat_l, case["dots"] + case["lines"]):
            err = abs(a - b)
            worst = max(worst, err)
            values += 1
            if err > tol:
                ok = False
    if not ok:
        fails += 1
        print("FAIL", case["key"], len(dots), case["dotCount"], len(lines), case["lineCount"])

print(f"{len(g['cases']) - fails}/{len(g['cases'])} cases pass, {values} values, worst abs error {worst:.2e} (tolerance {tol})")
sys.exit(1 if fails else 0)
